const normalize = (s: string) => s.toLowerCase().replace(/ё/g, 'е').replace(/[\s-]+/g, ' ').trim();

export function findSettlement(name: string): Settlement | undefined {
  const n = normalize(name);
  return SETTLEMENTS.find((s) => normalize(s.name) === n);
}

export function searchSettlements(query: string, limit = 8): Settlement[] {
  const q = normalize(query);
  if (!q) return [];
  const matches = SETTLEMENTS.filter((s) => [s.name, ...(s.aliases ?? [])].some((v) => normalize(v).includes(q)));
  // Сначала те, что начинаются с запроса.
  matches.sort((a, b) => Number(!normalize(a.name).startsWith(q)) - Number(!normalize(b.name).startsWith(q)));
  return matches.slice(0, limit);
}
